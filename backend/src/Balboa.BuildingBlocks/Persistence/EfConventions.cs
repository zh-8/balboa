using System.Linq.Expressions;
using System.Reflection;
using Balboa.BuildingBlocks.Outbox;
using Balboa.SharedKernel;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;

namespace Balboa.BuildingBlocks.Persistence;

/// <summary>EF Core conventions shared by every module's DbContext.</summary>
public static class EfConventions
{
    /// <summary>
    /// Maps every <see cref="IStronglyTypedId{TSelf}"/> struct in <paramref name="idAssembly"/> to a Guid column.
    /// Call from <c>DbContext.ConfigureConventions</c>.
    /// </summary>
    public static ModelConfigurationBuilder UseStronglyTypedIds(
        this ModelConfigurationBuilder configuration, Assembly idAssembly)
    {
        foreach (Type type in idAssembly.GetTypes())
        {
            bool isId = type is { IsValueType: true, IsAbstract: false }
                && type.GetInterfaces().Any(i =>
                    i.IsGenericType && i.GetGenericTypeDefinition() == typeof(IStronglyTypedId<>));
            if (isId)
            {
                configuration.Properties(type)
                    .HaveConversion(typeof(StronglyTypedIdConverter<>).MakeGenericType(type));
            }
        }

        return configuration;
    }

    /// <summary>Maps the outbox and inbox tables into the DbContext's schema.</summary>
    public static ModelBuilder ApplyOutboxInbox(this ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<OutboxMessage>(b =>
        {
            b.ToTable("outbox_messages");
            b.HasKey(m => m.Id);
            b.Property(m => m.Id).ValueGeneratedNever();
            b.Property(m => m.Type).HasMaxLength(500).IsRequired();
            b.Property(m => m.Payload).IsRequired();
            b.Property(m => m.LastError).HasMaxLength(2000);
            b.HasIndex(m => m.ProcessedOnUtc).HasFilter("\"ProcessedOnUtc\" IS NULL");
        });

        modelBuilder.Entity<InboxMessage>(b =>
        {
            b.ToTable("inbox_messages");
            b.HasKey(m => new { m.EventId, m.Consumer });
            b.Property(m => m.Consumer).HasMaxLength(300);
        });

        return modelBuilder;
    }

    /// <summary>Strongly-typed ids are assigned by the domain, never generated by the database.</summary>
    public static PropertyBuilder<TId> HasStronglyTypedIdKey<TId>(this PropertyBuilder<TId> property)
        where TId : struct, IStronglyTypedId<TId> =>
        property.ValueGeneratedNever();
}

/// <summary>Guid conversion for a strongly-typed id. Built with expression trees because EF needs them.</summary>
public sealed class StronglyTypedIdConverter<TId>()
    : ValueConverter<TId, Guid>(ToProvider(), FromProvider())
    where TId : struct, IStronglyTypedId<TId>
{
    private static Expression<Func<TId, Guid>> ToProvider()
    {
        ParameterExpression id = Expression.Parameter(typeof(TId), "id");
        return Expression.Lambda<Func<TId, Guid>>(Expression.Property(id, nameof(IStronglyTypedId<>.Value)), id);
    }

    private static Expression<Func<Guid, TId>> FromProvider()
    {
        ParameterExpression value = Expression.Parameter(typeof(Guid), "value");
        MethodInfo from = typeof(TId).GetMethod(nameof(IStronglyTypedId<>.From), [typeof(Guid)])
            ?? throw new InvalidOperationException(
                $"{typeof(TId).Name} must declare a public static From(Guid) method.");
        return Expression.Lambda<Func<Guid, TId>>(Expression.Call(from, value), value);
    }
}
